#!/usr/bin/env node
/**
 * Compiles docs/course-authoring-guide.md into src/guides/course-authoring-guide.generated.ts.
 *
 * The hosted MCP image is built from packages/ only (docs/ and *.md are dockerignored), so the guide
 * has to travel inside the package as source. Edit the markdown in docs/, run this, commit both.
 * A test fails if the generated copy no longer matches the markdown.
 */
const fs = require("fs");
const path = require("path");

const source = path.join(
  __dirname,
  "..",
  "..",
  "..",
  "docs",
  "course-authoring-guide.md",
);
const target = path.join(
  __dirname,
  "..",
  "src",
  "guides",
  "course-authoring-guide.generated.ts",
);

const guide = fs.readFileSync(source, "utf8");
const output =
  "// GENERATED by scripts/sync-course-guide.js from docs/course-authoring-guide.md. Do not edit by hand:\n" +
  "// edit the markdown, then run `npm run sync:guide -w packages/mcp`.\n" +
  `export const COURSE_AUTHORING_GUIDE =\n  ${JSON.stringify(guide)};\n`;

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(
  `wrote ${path.relative(process.cwd(), target)} (${guide.length} characters)`,
);
